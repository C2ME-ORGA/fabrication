<?php

namespace App\Models;

use App\Enums\WorkOrderPriority;
use App\Enums\WorkOrderStatus;
use Database\Factories\WorkOrderFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

#[Fillable([
    'job_id',
    'title',
    'description',
    'priority',
    'planned_start_at',
    'planned_end_at',
    'notes',
    'responsible_id',
])]
class WorkOrder extends Model
{
    /** @use HasFactory<WorkOrderFactory> */
    use HasFactory;

    /**
     * Fields that are never mass assignable: the number is generated by the
     * server and the lifecycle fields are only written by WorkOrderService.
     */
    public const PROTECTED_FIELDS = [
        'number',
        'status',
        'actual_start_at',
        'actual_end_at',
        'created_by',
        'released_by',
        'released_at',
        'responsible_id',
        'be_approved_by',
        'be_approved_at',
        'be_approval_batch_id',
        'be_approval_snapshot_id',
    ];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'status' => WorkOrderStatus::class,
            'priority' => WorkOrderPriority::class,
            'planned_start_at' => 'datetime',
            'planned_end_at' => 'datetime',
            'actual_start_at' => 'datetime',
            'actual_end_at' => 'datetime',
            'released_at' => 'datetime',
        ];
    }

    /**
     * @return BelongsTo<Job, $this>
     */
    public function job(): BelongsTo
    {
        return $this->belongsTo(Job::class);
    }

    /**
     * Documents attached directly to this work order.
     *
     * @return HasMany<Document, $this>
     */
    public function documents(): HasMany
    {
        return $this->hasMany(Document::class);
    }

    /**
     * Pièces et repères de la nomenclature de cet OF.
     *
     * @return HasMany<WorkOrderItem, $this>
     */
    public function items(): HasMany
    {
        return $this->hasMany(WorkOrderItem::class);
    }

    /**
     * Historique des imports de nomenclature confirmés pour cet OF.
     *
     * @return HasMany<WorkOrderBomImport, $this>
     */
    public function bomImports(): HasMany
    {
        return $this->hasMany(WorkOrderBomImport::class)->latest('imported_at');
    }

    /**
     * Frozen document references captured at release and re-review time.
     *
     * @return HasMany<WorkOrderDocumentSnapshot, $this>
     */
    public function documentSnapshots(): HasMany
    {
        return $this->hasMany(WorkOrderDocumentSnapshot::class)->latest('captured_at');
    }

    /**
     * Journal d'audit immuable des actions effectuées sur cet OF.
     *
     * @return HasMany<WorkOrderAuditLog, $this>
     */
    public function auditLogs(): HasMany
    {
        return $this->hasMany(WorkOrderAuditLog::class)->latest('created_at');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function creator(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function releaser(): BelongsTo
    {
        return $this->belongsTo(User::class, 'released_by');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function responsible(): BelongsTo
    {
        return $this->belongsTo(User::class, 'responsible_id');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function beApprover(): BelongsTo
    {
        return $this->belongsTo(User::class, 'be_approved_by');
    }

    public function isLocked(): bool
    {
        return $this->status->isLocked();
    }

    /**
     * Indique si au moins une pièce porte une production ou un rebut.
     * Ce contrôle empêche la suppression d'un OF de perdre cet historique.
     */
    public function hasRecordedItemProduction(): bool
    {
        return $this->items()
            ->where(function (Builder $query): void {
                $query->where('quantity_produced', '>', 0)
                    ->orWhere('quantity_rejected', '>', 0);
            })
            ->exists();
    }

    public function canTransitionTo(WorkOrderStatus $status): bool
    {
        return $this->status->canTransitionTo($status);
    }

    public function scopeForJob(Builder $query, Job|int $job): void
    {
        $query->where('job_id', $job instanceof Job ? $job->getKey() : $job);
    }
}
