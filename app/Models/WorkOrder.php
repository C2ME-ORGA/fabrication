<?php

namespace App\Models;

use App\Enums\WorkOrderPriority;
use App\Enums\WorkOrderStatus;
use Database\Factories\WorkOrderFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

#[Fillable([
    'job_id',
    'title',
    'description',
    'priority',
    'planned_start_at',
    'planned_end_at',
    'notes',
    'responsible_id',
])]
class WorkOrder extends Model
{
    /** @use HasFactory<WorkOrderFactory> */
    use HasFactory;

    /**
     * Fields that are never mass assignable: the number is generated by the
     * server and the lifecycle fields are only written by WorkOrderService.
     */
    public const PROTECTED_FIELDS = [
        'number',
        'status',
        'actual_start_at',
        'actual_end_at',
        'created_by',
        'released_by',
        'released_at',
        'responsible_id',
        'be_approved_by',
        'be_approved_at',
        'be_approval_batch_id',
        'be_approval_snapshot_id',
        'workshop_routing_id',
    ];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'status' => WorkOrderStatus::class,
            'priority' => WorkOrderPriority::class,
            'planned_start_at' => 'datetime',
            'planned_end_at' => 'datetime',
            'actual_start_at' => 'datetime',
            'actual_end_at' => 'datetime',
            'released_at' => 'datetime',
        ];
    }

    /**
     * @return BelongsTo<Job, $this>
     */
    public function job(): BelongsTo
    {
        return $this->belongsTo(Job::class);
    }

    /**
     * Documents attached directly to this work order.
     *
     * @return HasMany<Document, $this>
     */
    public function documents(): HasMany
    {
        return $this->hasMany(Document::class);
    }

    /**
     * Pièces et repères de la nomenclature de cet OF.
     *
     * @return HasMany<WorkOrderItem, $this>
     */
    public function items(): HasMany
    {
        return $this->hasMany(WorkOrderItem::class);
    }

    /**
     * Historique des imports de nomenclature confirmés pour cet OF.
     *
     * @return HasMany<WorkOrderBomImport, $this>
     */
    public function bomImports(): HasMany
    {
        return $this->hasMany(WorkOrderBomImport::class)->latest('imported_at');
    }

    /**
     * Gamme modèle utilisée pour générer les opérations de cet OF.
     *
     * @return BelongsTo<WorkshopRouting, $this>
     */
    public function workshopRouting(): BelongsTo
    {
        return $this->belongsTo(WorkshopRouting::class);
    }

    /**
     * Opérations de fabrication copiées dans l'OF, dans l'ordre d'affichage.
     *
     * @return HasMany<WorkOrderOperation, $this>
     */
    public function operations(): HasMany
    {
        return $this->hasMany(WorkOrderOperation::class)->orderBy('position')->orderBy('id');
    }

    /**
     * La gamme et les opérations d'un OF ne sont modifiables que tant que
     * l'OF n'a pas été libéré (brouillon ou prêt).
     */
    public function isRoutingEditable(): bool
    {
        return in_array($this->status, [WorkOrderStatus::Draft, WorkOrderStatus::Ready], true);
    }

    /**
     * Une fois libéré, l'OF et ses opérations sont protégés contre les
     * modifications ordinaires.
     */
    public function isRoutingLocked(): bool
    {
        return ! $this->isRoutingEditable();
    }

    /**
     * L'exécution des opérations est possible après libération de l'OF.
     */
    public function allowsOperationExecution(): bool
    {
        return $this->status->allowsOperationExecution();
    }

    /**
     * Frozen document references captured at release and re-review time.
     *
     * @return HasMany<WorkOrderDocumentSnapshot, $this>
     */
    public function documentSnapshots(): HasMany
    {
        return $this->hasMany(WorkOrderDocumentSnapshot::class)->latest('captured_at');
    }

    /**
     * Journal d'audit immuable des actions effectuées sur cet OF.
     *
     * @return HasMany<WorkOrderAuditLog, $this>
     */
    public function auditLogs(): HasMany
    {
        return $this->hasMany(WorkOrderAuditLog::class)->latest('created_at');
    }

    /**
     * Journal d'audit des opérations et des affectations de gamme.
     *
     * @return HasMany<WorkOrderOperationAuditLog, $this>
     */
    public function operationAuditLogs(): HasMany
    {
        return $this->hasMany(WorkOrderOperationAuditLog::class)->latest('created_at');
    }

    /**
     * Plan qualité généré pour cet ordre de fabrication.
     *
     * @return HasMany<WorkOrderQualityControl, $this>
     */
    public function qualityControls(): HasMany
    {
        return $this->hasMany(WorkOrderQualityControl::class)
            ->orderBy('position')
            ->orderBy('id');
    }

    /**
     * Résultats qualité enregistrés sur cet ordre de fabrication.
     *
     * @return HasMany<QualityControlResult, $this>
     */
    public function qualityResults(): HasMany
    {
        return $this->hasMany(QualityControlResult::class);
    }

    /**
     * Non-conformités rattachées à cet ordre de fabrication.
     *
     * @return HasMany<NonConformity, $this>
     */
    public function nonConformities(): HasMany
    {
        return $this->hasMany(NonConformity::class)->latest('id');
    }

    /**
     * Dérogations qualité rattachées à cet ordre de fabrication.
     *
     * @return HasMany<QualityDeviation, $this>
     */
    public function qualityDeviations(): HasMany
    {
        return $this->hasMany(QualityDeviation::class)->latest('id');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function creator(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function releaser(): BelongsTo
    {
        return $this->belongsTo(User::class, 'released_by');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function responsible(): BelongsTo
    {
        return $this->belongsTo(User::class, 'responsible_id');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function beApprover(): BelongsTo
    {
        return $this->belongsTo(User::class, 'be_approved_by');
    }

    public function isLocked(): bool
    {
        return $this->status->isLocked();
    }

    /**
     * Indique si au moins une pièce porte une production ou un rebut.
     * Ce contrôle empêche la suppression d'un OF de perdre cet historique.
     */
    public function hasRecordedItemProduction(): bool
    {
        return $this->items()
            ->where(function (Builder $query): void {
                $query->where('quantity_produced', '>', 0)
                    ->orWhere('quantity_rejected', '>', 0);
            })
            ->exists();
    }

    public function canTransitionTo(WorkOrderStatus $status): bool
    {
        return $this->status->canTransitionTo($status);
    }

    public function scopeForJob(Builder $query, Job|int $job): void
    {
        $query->where('job_id', $job instanceof Job ? $job->getKey() : $job);
    }
}
